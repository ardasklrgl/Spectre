import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import ts from 'typescript';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
const base=new URL('../',import.meta.url);
const source=await readFile(new URL('src/Markdown.tsx',base),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const location=new URL('node_modules/.cache/betterpad-tests/',base);
await mkdir(location,{recursive:true});await writeFile(new URL('Markdown.mjs',location),output);
const {Markdown,safeMarkdownUrl}=await import(new URL('Markdown.mjs',location));
const render=text=>renderToStaticMarkup(createElement(Markdown,{text,onError:e=>{throw e}}));
const html=render('# Heading\n\n**Bold** and *italic* and ~~removed~~.\n\n- [x] Done\n- [ ] Todo\n\n```js\nconst a = "<tag>";\n```\n\n| A | B |\n|---|---|\n| 1 | 2 |');
for(const tag of ['<h1>Heading</h1>','<strong>','<em>','<del>','<pre>','<table>'])assert.ok(html.includes(tag),tag);
assert.equal((html.match(/type="checkbox"/g)||[]).length,2,'one checkbox per task');
assert.ok(html.includes('&lt;tag&gt;'),'code remains literal text');
const unsafe=render('<script>alert(1)</script>\n\n[bad](javascript:alert%281%29)');
assert.ok(!unsafe.includes('<script>'));assert.ok(!unsafe.includes('href="javascript:'));assert.ok(unsafe.includes('&lt;script&gt;'));
assert.equal(safeMarkdownUrl('data:text/html,<script>'),null);assert.equal(safeMarkdownUrl('javascript:alert(1)'),null);assert.ok(safeMarkdownUrl('https://example.com'));
console.log('PASS: Markdown formatting, tables, task lists, literal code, and unsafe HTML/URL handling');
